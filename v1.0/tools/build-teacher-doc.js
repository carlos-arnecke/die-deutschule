/* Regenerates "for-teachers-review.md" from the item bank.
 *
 *   node tools/build-teacher-doc.js
 *
 * Run it after ANY change to data/items.js so the teachers' copy always
 * matches what the test actually asks.
 */

var fs = require('fs');
var path = require('path');

var root = path.join(__dirname, '..');
eval(fs.readFileSync(path.join(root, 'data/items.js'), 'utf8'));

var LEVELS = ['A1', 'A2', 'B1', 'B2', 'C1'];

var LEVEL_BLURB = {
  A1: 'present tense, sein/haben, articles, W-questions, verb-second word order, accusative',
  A2: 'Perfekt, modal verbs, dative, separable verbs, comparatives, weil/wenn clauses',
  B1: 'Konjunktiv II, relative clauses, present passive, adjective endings, genitive prepositions, purpose clauses',
  B2: 'concessive connectors, modal passive, je/desto, genitive relative pronouns, als ob, participial attributes, precise collocation',
  C1: 'idiom, Konjunktiv I, nominal style, conditional inversion, register, formal discourse markers'
};

var out = [];
var W = function (s) { out.push(s === undefined ? '' : s); };

W('# The German level test — a review by our teachers');
W();
W('*Generated from the live question bank. Please do not edit this file by hand —');
W('tell us what to change and we will update the test itself.*');
W();
W('---');
W();
W('## What this is');
W();
W('A short online test that tells a person which level they should join: A1, A2, B1, B2 or C1.');
W('It sits on our website to bring in new students, and we will also use it on a tablet at the');
W('front desk when someone walks in.');
W();
W('**It is not an exam.** It does not replace what you do in the classroom, and it does not decide');
W('anything on its own — we always confirm the level with the student before they start. Its job is');
W('to get people close enough to the right course that the conversation starts well.');
W();
W('It tests **reading, grammar and vocabulary only.** There is no speaking, writing or listening in it.');
W('The result page says so plainly.');
W();
W('## What we need from you');
W();
W('Four questions, for each of the 50 items below. It should take about 45 minutes.');
W();
W('1. **Is it at the right level?** Would a student at this level get it right, and a student one level');
W('   below get it wrong?');
W('2. **Is there exactly one right answer?** *This is the one that matters most.* If a native speaker');
W('   could defend one of the other options, the question is broken and has to go.');
W('3. **Is the German natural?** Something a person would actually say or write.');
W('4. **Is anything important missing?** If a level tests something we always teach and it is not here,');
W('   tell us.');
W();
W('## How to tell us');
W();
W('Every question has a code — `B1-06`, `A2-03`. Write the code and what is wrong with it. That is enough.');
W('Print this and mark it up, or send the list by email. You do not need to suggest a replacement,');
W('though we will take one gladly.');
W();
W('---');
W();
W('## How the test decides someone\'s level');
W();
W('**The test is in sets of 6 questions.** One set per level.');
W();
W('It starts by asking the person how much German they already know, and begins at roughly that level.');
W('Then it moves:');
W();
W('| Out of 6 questions | What the test does |');
W('|---|---|');
W('| 5 or 6 right | They know this level — go **up** a set |');
W('| 3 or 4 right | They are in the middle of this level — **stop here** |');
W('| 0, 1 or 2 right | Too hard — go **down** a set |');
W();
W('Most people answer 2 or 3 sets, so 12 to 18 questions in total.');
W();
W('**The level we report is the level they should join** — the first level they have *not* mastered.');
W('Someone who gets all the A2 questions right and half the B1 questions right is told **B1**,');
W('because B1 is what they still need to learn.');
W();
W('### An example');
W();
W('Someone says they can hold a conversation, so the test starts at B1.');
W();
W('- **B1 set:** 6 out of 6. They know B1 — go up.');
W('- **B2 set:** 3 out of 6. They are part-way through B2 — stop.');
W('- **Result: B2.** They join a B2 course.');
W();
W('Had they scored 1 out of 6 on that first B1 set, the test would have gone *down* to A2 instead.');
W('It corrects itself in both directions, so it does not matter much if someone misjudges themselves');
W('at the start — it only changes how many questions they answer.');
W();
W('### One thing this means for your review');
W();
W('There are **10 questions per level in this document, but each person only sees 6 of them**, picked');
W('at random. We do that so two people sitting next to each other do not get the same test.');
W();
W('So the ten questions at a level need to be **about equally hard**. If one of them is much harder');
W('than the rest, some students get an unfairly difficult set purely by luck. If you spot an odd one');
W('out, that is exactly the kind of thing we need to hear.');
W();
W('---');
W();
W('## The questions');
W();
W('✅ marks the correct answer.');
W();

LEVELS.forEach(function (lvl) {
  var pool = ITEM_BANK[lvl] || [];
  W('---');
  W();
  W('## ' + lvl + ' — ' + pool.length + ' questions');
  W();
  W('*Meant to test: ' + LEVEL_BLURB[lvl] + '.*');
  W();

  pool.forEach(function (it) {
    W('### `' + it.id + '`  ·  ' + it.skill + '  ·  ' + it.tag);
    W();
    if (it.passage) {
      W(it.passage.split('\n').map(function (line) { return line.trim() ? '> ' + line : '>'; }).join('\n'));
      W();
    }
    W('**' + it.prompt + '**');
    W();
    it.options.forEach(function (o, i) {
      W((i === it.answer ? '- ✅ ' : '- ') + o);
    });
    W();
    if (it.note) { W('*Note for you: ' + it.note + '*'); W(); }
  });
});

W('---');
W();
W('## Thank you');
W();
W('Once we have your notes we will fix the questions and send this back for a second look.');
W('Any question the two of you disagree about, we will drop rather than argue over — a question');
W('teachers cannot agree on is not one we should be asking students.');
W();

var file = path.join(root, 'for-teachers-review.md');
fs.writeFileSync(file, out.join('\n'), 'utf8');

var count = LEVELS.reduce(function (n, l) { return n + (ITEM_BANK[l] || []).length; }, 0);
console.log('Wrote ' + file + ' (' + count + ' questions)');
